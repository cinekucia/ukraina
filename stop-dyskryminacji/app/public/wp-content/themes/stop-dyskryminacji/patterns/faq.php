		<details>
			<summary>Czy zgłoszenie jest anonimowe?</summary>
			<p>Nie w pełni, ale nie musisz podawać nazwiska. W formularzu wpisujesz imię — nie musi to być Twoje prawdziwe imię. Wymagany jest tylko adres e-mail, bo bez niego nie mamy jak odpowiedzieć. Telefon jest opcjonalny. Nie pytamy o nazwisko, PESEL ani nazwę pracodawcy.</p>
		</details>

		<details>
			<summary>Czy mój pracodawca się o tym dowie?</summary>
			<p>Nie. Nie kontaktujemy się z pracodawcą i nie przekazujemy zgłoszeń żadnej instytucji. Zgłoszenie trafia wyłącznie do upoważnionych osób z zespołu projektu. Każde otwarcie zgłoszenia jest odnotowywane w rejestrze dostępu.</p>
		</details>

		<details>
			<summary>Ile czeka się na odpowiedź?</summary>
			<p>Do 5 dni roboczych. Potwierdzenie przyjęcia zgłoszenia dostajesz e-mailem od razu po wysłaniu. Jeśli sprawa wymaga pilnej reakcji — na przykład grozi Ci zwolnienie w najbliższych dniach — napisz o tym w pierwszym zdaniu opisu.</p>
		</details>

		<details>
			<summary>Czy to jest porada prawna?</summary>
			<p>Odpowiedź z modułu zgłoszeniowego to informacja o możliwych krokach, a nie opinia prawna w konkretnej sprawie. W ramach projektu prowadzimy natomiast bezpłatne poradnictwo prawne i psychologiczne — po zgłoszeniu wskażemy, jak z niego skorzystać.</p>
		</details>

		<details>
			<summary>Jak długo przechowujecie moje dane?</summary>
			<p>Treść zgłoszenia jest szyfrowana i usuwana automatycznie po upływie okresu retencji podanego w klauzuli pod formularzem. Możesz w każdej chwili poprosić o wcześniejsze usunięcie swojego zgłoszenia — szczegóły znajdziesz w <a href="/polityka-prywatnosci/">polityce prywatności</a>.</p>
		</details>

		<details>
			<summary>Nie jestem pewna, czy to była dyskryminacja. Mogę napisać?</summary>
			<p>Tak, i to jest jeden z najczęstszych powodów kontaktu. Nie musisz samodzielnie kwalifikować sytuacji prawnie. Opisz, co się stało — ocena, czy przepisy o równym traktowaniu mają tu zastosowanie, należy do nas.</p>
