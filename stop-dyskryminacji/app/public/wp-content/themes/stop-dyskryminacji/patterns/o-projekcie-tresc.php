<h2 class="wp-block-heading">Cel projektu</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Celem projektu jest wzmocnienie od 1 sierpnia 2026 r. do 29 lutego 2028 r. równości szans i promowanie kultury włączającej na wielkopolskim rynku pracy poprzez podniesienie kompetencji osób odpowiedzialnych za zarządzanie i politykę kadrową w przedsiębiorstwach, podniesienie kompetencji osób doświadczających dyskryminacji w zakresie przysługujących im praw i sposobów reagowania na nierówne traktowanie, poprawę sytuacji społecznej osób doświadczających dyskryminacji, wzrost świadomości przedstawicieli przedsiębiorstw na temat dyskryminacji w zatrudnieniu oraz zwiększenie dostępności wiedzy i praktycznych narzędzi wspierających równe traktowanie.</p>
<!-- /wp:paragraph -->

