<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Grupy docelowe</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Projekt skierowany jest do 330 osób uczących się, pracujących lub mieszkających w województwie wielkopolskim, a także do osób bezdomnych przebywających na tym obszarze, w tym: 100 osób doświadczających dyskryminacji na rynku pracy ze względu na płeć, wiek, narodowość lub niepełnosprawność oraz 230 pracowników przedsiębiorstw odpowiedzialnych za zarządzanie i politykę kadrową. Pierwszeństwo mają osoby doświadczające dyskryminacji wielokrotnej oraz przedstawiciele mikro i małych firm.</p>
